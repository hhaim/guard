package guardsched

import "testing"

func TestPyRandomMatchesCPythonSeed3(t *testing.T) {
	want := []float64{
		0.23796462709189137, 0.5442292252959519, 0.36995516654807925,
		0.6039200385961945, 0.625720304108054, 0.06552885923981311,
		0.013167991554874137, 0.83746908209646, 0.25935401432800764,
		0.23433096104669637, 0.9956448355104628, 0.47026350752244794,
		0.8364614512743888, 0.47635320869933495, 0.6390681405441619,
	}
	r := NewPyRandom(3)
	for i, w := range want {
		got := r.Random()
		if got != w {
			t.Fatalf("i=%d got=%.17g want=%.17g", i, got, w)
		}
	}
}
